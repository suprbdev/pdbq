package e2e

import (
	"context"
	"encoding/json"
	"strings"
	"testing"

	"github.com/suprbdev/pdbq/internal/config"
)

// TestTemporal covers PostgreSQL 18 temporal keys: a WITHOUT OVERLAPS
// primary key, a PERIOD foreign key joined by range overlap, and a NOT
// ENFORCED foreign key. The tables mirror temporalTables in
// internal/compile.
func TestTemporal(t *testing.T) {
	conn := testConn(t)
	var version int
	if err := conn.QueryRow(context.Background(), `SELECT current_setting('server_version_num')::int`).Scan(&version); err != nil {
		t.Fatal(err)
	}
	if version < 180000 {
		t.Skipf("temporal keys need PostgreSQL 18+, server_version_num is %d", version)
	}
	execAll(t, conn,
		`CREATE EXTENSION IF NOT EXISTS btree_gist`,
		`CREATE TABLE room_bookings (
			room_id  integer NOT NULL,
			valid_at daterange NOT NULL,
			guest    text NOT NULL,
			PRIMARY KEY (room_id, valid_at WITHOUT OVERLAPS)
		)`,
		`CREATE TABLE booking_notes (
			id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			room_id   integer NOT NULL,
			valid_at  daterange NOT NULL,
			note      text NOT NULL,
			author_id integer NOT NULL,
			FOREIGN KEY (room_id, PERIOD valid_at) REFERENCES room_bookings (room_id, PERIOD valid_at),
			FOREIGN KEY (author_id) REFERENCES users (id) NOT ENFORCED
		)`,
		`CREATE TABLE note_pins (
			note_id integer PRIMARY KEY REFERENCES booking_notes (id) ON DELETE RESTRICT
		)`,
		`INSERT INTO room_bookings VALUES
			(1, '[2026-03-01,2026-03-05)', 'Ada'),
			(1, '[2026-03-05,2026-03-10)', 'Grace'),
			(2, '[2026-03-02,2026-03-04)', 'Linus')`,
		`INSERT INTO booking_notes (id, room_id, valid_at, note, author_id) VALUES
			(1, 1, '[2026-03-03,2026-03-07)', 'Spans both', 1),
			(2, 1, '[2026-03-02,2026-03-03)', 'Short', 999)`,
		`SELECT setval(pg_get_serial_sequence('booking_notes', 'id'), 2)`,
		`INSERT INTO note_pins VALUES (2)`,
	)
	t.Cleanup(func() {
		_, _ = conn.Exec(context.Background(), `DROP TABLE note_pins, booking_notes, room_bookings`)
	})

	hs := testServer(t, func(c *config.Config) {
		c.Server.ExposeSchema = true
		c.Filters.IndexedOnly = false
	})
	query := func(t *testing.T, q, want string) {
		t.Helper()
		res := post(t, hs.URL, q, nil)
		requireNoErrors(t, res)
		b, _ := json.Marshal(res.Data)
		if got := normalize(t, b); got != want {
			t.Errorf("got  %s\nwant %s", got, want)
		}
	}

	t.Run("PERIOD foreign key joins every overlapping parent", func(t *testing.T) {
		query(t, `{ allBookingNotes(orderBy: ID_ASC) { nodes {
			note
			author { email }
			roomBookingsByRoomIdAndValidAt { totalCount nodes { guest } }
		} } }`, `{"allBookingNotes":{"nodes":[`+
			`{"author":{"email":"ada@example.com"},"note":"Spans both","roomBookingsByRoomIdAndValidAt":{"nodes":[{"guest":"Ada"},{"guest":"Grace"}],"totalCount":2}},`+
			`{"author":null,"note":"Short","roomBookingsByRoomIdAndValidAt":{"nodes":[{"guest":"Ada"}],"totalCount":1}}]}}`)
	})

	t.Run("backward relation over a PERIOD foreign key", func(t *testing.T) {
		query(t, `{ allRoomBookings { nodes { guest bookingNotesByRoomIdAndValidAt { nodes { note } } } } }`,
			`{"allRoomBookings":{"nodes":[`+
				`{"bookingNotesByRoomIdAndValidAt":{"nodes":[{"note":"Spans both"},{"note":"Short"}]},"guest":"Ada"},`+
				`{"bookingNotesByRoomIdAndValidAt":{"nodes":[{"note":"Spans both"}]},"guest":"Grace"},`+
				`{"bookingNotesByRoomIdAndValidAt":{"nodes":[]},"guest":"Linus"}]}}`)
	})

	t.Run("temporal key lookups", func(t *testing.T) {
		sdl, err := httpGet(hs.URL + "/schema.graphql")
		if err != nil {
			t.Fatal(err)
		}
		for _, absent := range []string{"roomBookingByRoomIdAndValidAt(", "upsertRoomBooking"} {
			if strings.Contains(string(sdl), absent) {
				t.Errorf("SDL has %q", absent)
			}
		}
		query(t, `{
			during: roomBookingByRoomId(roomId: 1, at: "2026-03-06") { guest }
			boundary: roomBookingByRoomId(roomId: 1, at: "2026-03-05") { guest }
			outside: roomBookingByRoomId(roomId: 1, at: "2026-04-01") { guest }
		}`, `{"boundary":{"guest":"Grace"},"during":{"guest":"Grace"},"outside":null}`)
	})

	t.Run("nodeId over a temporal primary key", func(t *testing.T) {
		res := post(t, hs.URL, `{ allRoomBookings(condition: {guest: "Grace"}) { nodes { nodeId } } }`, nil)
		requireNoErrors(t, res)
		var page struct {
			Nodes []struct {
				NodeID string `json:"nodeId"`
			} `json:"nodes"`
		}
		mustUnmarshal(t, res.Data["allRoomBookings"], &page)
		if len(page.Nodes) != 1 {
			t.Fatalf("nodes = %+v", page.Nodes)
		}
		res = post(t, hs.URL, `query($id: ID!) { node(nodeId: $id) { ... on RoomBooking { guest validAt { start { value } end { value inclusive } } } } }`,
			map[string]any{"id": page.Nodes[0].NodeID})
		requireNoErrors(t, res)
		if got := normalize(t, res.Data["node"]); got != `{"guest":"Grace","validAt":{"end":{"inclusive":false,"value":"2026-03-10"},"start":{"value":"2026-03-05"}}}` {
			t.Errorf("node: got %s", got)
		}
	})

	t.Run("keyset pagination over a temporal primary key", func(t *testing.T) {
		res := post(t, hs.URL, `{ allRoomBookings(first: 1) { pageInfo { endCursor } nodes { guest } } }`, nil)
		requireNoErrors(t, res)
		var page struct {
			PageInfo struct {
				EndCursor string `json:"endCursor"`
			} `json:"pageInfo"`
		}
		mustUnmarshal(t, res.Data["allRoomBookings"], &page)
		res = post(t, hs.URL, `query($after: Cursor) { allRoomBookings(first: 5, after: $after) { nodes { guest } } }`,
			map[string]any{"after": page.PageInfo.EndCursor})
		requireNoErrors(t, res)
		if got := normalize(t, res.Data["allRoomBookings"]); got != `{"nodes":[{"guest":"Grace"},{"guest":"Linus"}]}` {
			t.Errorf("after first page: got %s", got)
		}
	})

	t.Run("relation filters and ordering", func(t *testing.T) {
		query(t, `{
			someGrace: allBookingNotes(filter: {roomBookingsByRoomIdAndValidAt: {some: {guest: {equalTo: "Grace"}}}}) { nodes { note } }
			everyAda: allBookingNotes(filter: {roomBookingsByRoomIdAndValidAt: {every: {guest: {equalTo: "Ada"}}}}) { nodes { note } }
			dangling: allBookingNotes(filter: {authorExists: false}) { nodes { note } }
			noteless: allRoomBookings(filter: {bookingNotesByRoomIdAndValidAtExist: false}) { nodes { guest } }
			byParent: allBookingNotes(orderBy: [ROOM_BOOKINGS_BY_ROOM_ID_AND_VALID_AT__GUEST_DESC]) { nodes { note } }
		}`, `{"byParent":{"nodes":[{"note":"Spans both"},{"note":"Short"}]},`+
			`"dangling":{"nodes":[{"note":"Short"}]},`+
			`"everyAda":{"nodes":[{"note":"Short"}]},`+
			`"noteless":{"nodes":[{"guest":"Linus"}]},`+
			`"someGrace":{"nodes":[{"note":"Spans both"}]}}`)
	})

	t.Run("integrity errors", func(t *testing.T) {
		prod := testServer(t, func(c *config.Config) { c.Errors.Detail = "prod" })
		cases := []struct{ name, query, code, msg string }{
			{"overlapping temporal key", `mutation { createRoomBooking(input: {roomId: 1, validAt: {start: {value: "2026-03-02", inclusive: true}, end: {value: "2026-03-03", inclusive: false}}, guest: "Overlap"}) { roomBooking { guest } } }`,
				"23P01", `conflicting key value violates exclusion constraint "room_bookings_pkey"`},
			{"period not covered", `mutation { createBookingNote(input: {roomId: 2, validAt: {start: {value: "2030-01-01", inclusive: true}, end: {value: "2030-01-02", inclusive: false}}, note: "orphan", authorId: 1}) { bookingNote { id } } }`,
				"23503", `insert or update on table "booking_notes" violates foreign key constraint "booking_notes_room_id_valid_at_fkey"`},
			{"restrict", `mutation { deleteBookingNoteById(id: 2) { bookingNote { id } } }`,
				"23001", `update or delete on table "booking_notes" violates RESTRICT setting of foreign key constraint "note_pins_note_id_fkey" on table "note_pins"`},
		}
		for _, tc := range cases {
			t.Run(tc.name, func(t *testing.T) {
				body, _ := json.Marshal(map[string]any{"query": tc.query})
				raw, err := httpPost(prod.URL+"/graphql", body)
				if err != nil {
					t.Fatal(err)
				}
				var res struct {
					Errors []struct {
						Message    string         `json:"message"`
						Extensions map[string]any `json:"extensions"`
					} `json:"errors"`
				}
				if err := json.Unmarshal(raw, &res); err != nil {
					t.Fatalf("bad response %s: %v", raw, err)
				}
				if len(res.Errors) != 1 || res.Errors[0].Message != tc.msg || res.Errors[0].Extensions["code"] != tc.code {
					t.Errorf("errors = %+v, want %s %q", res.Errors, tc.code, tc.msg)
				}
			})
		}
	})

	t.Run("nested mutations follow the PERIOD foreign key", func(t *testing.T) {
		query(t, `mutation { createBookingNote(input: {
			validAt: {start: {value: "2026-03-04", inclusive: true}, end: {value: "2026-03-06", inclusive: false}}, note: "Connected", authorId: 1,
			roomBookingsByRoomIdAndValidAt: {connectByRoomId: {roomId: 1}}
		}) { bookingNote { note roomId roomBookingsByRoomIdAndValidAt { nodes { guest } } } } }`,
			`{"createBookingNote":{"bookingNote":{"note":"Connected","roomBookingsByRoomIdAndValidAt":{"nodes":[{"guest":"Ada"},{"guest":"Grace"}]},"roomId":1}}}`)
		query(t, `mutation { createRoomBooking(input: {
			roomId: 3, validAt: {start: {value: "2026-05-01", inclusive: true}, end: {value: "2026-05-10", inclusive: false}}, guest: "Barbara",
			bookingNotesByRoomIdAndValidAt: {create: [{validAt: {start: {value: "2026-05-02", inclusive: true}, end: {value: "2026-05-03", inclusive: false}}, note: "Nested", authorId: 2}]}
		}) { roomBooking { guest bookingNotesByRoomIdAndValidAt { nodes { note roomId } } } } }`,
			`{"createRoomBooking":{"roomBooking":{"bookingNotesByRoomIdAndValidAt":{"nodes":[{"note":"Nested","roomId":3}]},"guest":"Barbara"}}}`)
	})

	t.Run("nested operations by the full temporal key", func(t *testing.T) {
		query(t, `mutation { updateRoomBookingByRoomIdAndValidAt(roomId: 1, validAt: {start: {value: "2026-03-05", inclusive: true}, end: {value: "2026-03-10", inclusive: false}},
			patch: {bookingNotesByRoomIdAndValidAt: {updateById: [{id: 1, bookingNotePatch: {note: "Spans both!"}}]}}) {
			roomBooking { bookingNotesByRoomIdAndValidAt(orderBy: ID_ASC) { nodes { note } } } } }`,
			`{"updateRoomBookingByRoomIdAndValidAt":{"roomBooking":{"bookingNotesByRoomIdAndValidAt":{"nodes":[{"note":"Spans both!"},{"note":"Connected"}]}}}}`)
		query(t, `mutation { createBookingNote(input: {
			validAt: {start: {value: "2026-03-06", inclusive: true}, end: {value: "2026-03-07", inclusive: false}}, note: "Keyed", authorId: 1,
			roomBookingsByRoomIdAndValidAt: {connectByRoomIdAndValidAt: {roomId: 1, validAt: {start: {value: "2026-03-05", inclusive: true}, end: {value: "2026-03-10", inclusive: false}}}}
		}) { bookingNote { roomId roomBookingsByRoomIdAndValidAt { nodes { guest } } } } }`,
			`{"createBookingNote":{"bookingNote":{"roomBookingsByRoomIdAndValidAt":{"nodes":[{"guest":"Grace"}]},"roomId":1}}}`)
	})

	t.Run("update by the full temporal key", func(t *testing.T) {
		query(t, `mutation { updateRoomBookingByRoomIdAndValidAt(roomId: 2, validAt: {start: {value: "2026-03-02", inclusive: true}, end: {value: "2026-03-04", inclusive: false}}, patch: {guest: "Linus T"}) { roomBooking { guest } } }`,
			`{"updateRoomBookingByRoomIdAndValidAt":{"roomBooking":{"guest":"Linus T"}}}`)
	})
}
