const (
	customRangeSchema      = "customrange_e2e"
	customRangeTypesSchema = "customrange types"
)

// TestCustomRanges covers range types created with CREATE TYPE ... AS RANGE.
// The types live in a schema that is neither introspected nor on the
// search_path, so the compiled constructors must be schema-qualified:
// floatrange (float8, with its floatmultirange) surfaces as FloatRange,
// slotrange (int4) shares IntRange, and moodrange (over an enum) keeps the
// String fallback.
func TestCustomRanges(t *testing.T) {
	url := os.Getenv("PDBQ_TEST_DATABASE_URL")
	if url == "" {
		t.Skip("PDBQ_TEST_DATABASE_URL not set; run `make test-e2e`")
	}
	ctx := context.Background()
	conn, err := pgx.Connect(ctx, url)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		_, _ = conn.Exec(ctx, `DROP SCHEMA IF EXISTS `+customRangeSchema+` CASCADE`)
		_, _ = conn.Exec(ctx, `DROP SCHEMA IF EXISTS "`+customRangeTypesSchema+`" CASCADE`)
		_ = conn.Close(ctx)
	})
	types := `"` + customRangeTypesSchema + `"`
	if _, err := conn.Exec(ctx, `
CREATE SCHEMA `+types+`;
CREATE TYPE `+types+`.floatrange AS RANGE (subtype = float8, subtype_diff = float8mi, multirange_type_name = `+types+`.floatmultirange);
CREATE TYPE `+types+`.slotrange AS RANGE (subtype = int4);
CREATE TYPE `+types+`.mood AS ENUM ('low', 'mid', 'high');
CREATE TYPE `+types+`.moodrange AS RANGE (subtype = `+types+`.mood);
CREATE SCHEMA `+customRangeSchema+`;
CREATE TABLE `+customRangeSchema+`.readings (
	id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	temp `+types+`.floatrange,
	temps `+types+`.floatmultirange,
	slot `+types+`.slotrange,
	moods `+types+`.moodrange
);
CREATE INDEX ON `+customRangeSchema+`.readings USING gist (temp);
CREATE INDEX ON `+customRangeSchema+`.readings USING gist (temps);
CREATE INDEX ON `+customRangeSchema+`.readings USING gist (slot);
INSERT INTO `+customRangeSchema+`.readings (temp, temps, slot, moods) VALUES
	('[1.5,2.5)', '{[0,1), [3,4)}', '[1,5)', '[low,mid)'),
	('[10,20]', '{[10,11)}', '[5,10)', '[mid,high]');
`); err != nil {
		t.Fatal(err)
	}
	hs := testServer(t, func(cfg *config.Config) { cfg.Schema.Schemas = []string{customRangeSchema} })

	ids := func(t *testing.T, filter string) []int {
		t.Helper()
		res := post(t, hs.URL, `{ allReadings(filter: `+filter+`, orderBy: ID_ASC) { nodes { id } } }`, nil)
		requireNoErrors(t, res)
		var c struct {
			Nodes []struct {
				ID int `json:"id"`
			} `json:"nodes"`
		}
		mustUnmarshal(t, res.Data["allReadings"], &c)
		out := []int{}
		for _, n := range c.Nodes {
			out = append(out, n.ID)
		}
		return out
	}

	t.Run("output", func(t *testing.T) {
		res := post(t, hs.URL, `{ readingById(id: 1) {
			temp { __typename start { value inclusive } end { value inclusive } }
			temps { start { value } end { value } }
			slot { __typename start { value } end { value } }
			moods
		} }`, nil)
		requireNoErrors(t, res)
		want := `{"temp":{"__typename":"FloatRange","start":{"value":1.5,"inclusive":true},"end":{"value":2.5,"inclusive":false}},` +
			`"temps":[{"start":{"value":0},"end":{"value":1}},{"start":{"value":3},"end":{"value":4}}],` +
			`"slot":{"__typename":"IntRange","start":{"value":1},"end":{"value":5}},"moods":"[low,mid)"}`
		var got, exp any
		mustUnmarshal(t, res.Data["readingById"], &got)
		if err := json.Unmarshal([]byte(want), &exp); err != nil {
			t.Fatal(err)
		}
		gb, _ := json.Marshal(got)
		eb, _ := json.Marshal(exp)
		if string(gb) != string(eb) {
			t.Errorf("readingById = %s\nwant %s", gb, eb)
		}
	})

	t.Run("filters", func(t *testing.T) {
		for _, tc := range []struct {
			name, filter string
			want         []int
		}{
			{"overlaps", `{temp: {overlaps: {start: {value: 2, inclusive: true}, end: {value: 12, inclusive: false}}}}`, []int{1, 2}},
			{"containsElement", `{temp: {containsElement: 15.5}}`, []int{2}},
			{"equalTo", `{temp: {equalTo: {start: {value: 1.5, inclusive: true}, end: {value: 2.5, inclusive: false}}}}`, []int{1}},
			{"multirange containsElement", `{temps: {containsElement: 3.5}}`, []int{1}},
			{"int subtype", `{slot: {containsElement: 7}}`, []int{2}},
		} {
			t.Run(tc.name, func(t *testing.T) {
				if got := ids(t, tc.filter); !slices.Equal(got, tc.want) {
					t.Errorf("%s = %v, want %v", tc.filter, got, tc.want)
				}
			})
		}
	})

	t.Run("create", func(t *testing.T) {
		res := post(t, hs.URL, `mutation { createReading(input: {
			temp: {start: {value: 0.25, inclusive: false}, end: {value: 0.75, inclusive: true}}
			temps: [{start: {value: 5, inclusive: true}, end: {value: 6, inclusive: false}}]
			slot: {start: {value: 2, inclusive: true}, end: {value: 3, inclusive: true}}
			moods: "[low,high]"
		}) { reading { temp { start { value inclusive } } slot { start { value } end { value inclusive } } moods } } }`, nil)
		requireNoErrors(t, res)
		var out struct {
			Reading struct {
				Temp struct {
					Start struct {
						Value     float64 `json:"value"`
						Inclusive bool    `json:"inclusive"`
					} `json:"start"`
				} `json:"temp"`
				Slot struct {
					Start struct{ Value int } `json:"start"`
					End   struct {
						Value     int  `json:"value"`
						Inclusive bool `json:"inclusive"`
					} `json:"end"`
				} `json:"slot"`
				Moods string `json:"moods"`
			} `json:"reading"`
		}
		mustUnmarshal(t, res.Data["createReading"], &out)
		r := out.Reading
		if r.Temp.Start.Value != 0.25 || r.Temp.Start.Inclusive {
			t.Errorf("temp start = %+v, want 0.25 exclusive", r.Temp.Start)
		}
		if r.Slot.Start.Value != 2 || r.Slot.End.Value != 3 || !r.Slot.End.Inclusive {
			t.Errorf("slot = %+v, want [2,3] (a custom range has no canonical function)", r.Slot)
		}
		if r.Moods != "[low,high]" {
			t.Errorf("moods = %q", r.Moods)
		}
		if got := ids(t, `{temps: {containsElement: 5.5}}`); !slices.Equal(got, []int{3}) {
			t.Errorf("created multirange not found: %v", got)
		}
	})
}

func TestCustomRangeConstructorsHidden(t *testing.T) {
	url := os.Getenv("PDBQ_TEST_DATABASE_URL")
	if url == "" {
		t.Skip("PDBQ_TEST_DATABASE_URL not set; run `make test-e2e`")
	}
	const schema = "rangector_e2e"
	ctx := context.Background()
	conn, err := pgx.Connect(ctx, url)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		_, _ = conn.Exec(ctx, `DROP SCHEMA IF EXISTS `+schema+` CASCADE`)
		_ = conn.Close(ctx)
	})
	if _, err := conn.Exec(ctx, `
CREATE SCHEMA `+schema+`;
CREATE TYPE `+schema+`.floatrange AS RANGE (subtype = float8, subtype_diff = float8mi, multirange_type_name = `+schema+`.floatmultirange);
CREATE TABLE `+schema+`.readings (id int PRIMARY KEY, temp `+schema+`.floatrange);
CREATE FUNCTION `+schema+`.visible_fn() RETURNS int LANGUAGE sql STABLE AS 'SELECT 1';
`); err != nil {
		t.Fatal(err)
	}
	hs := testServer(t, func(cfg *config.Config) { cfg.Schema.Schemas = []string{schema} })
	res := post(t, hs.URL, `{ __schema {
		queryType { fields { name } }
		mutationType { fields { name } }
	} }`, nil)
	requireNoErrors(t, res)
	var sch struct {
		QueryType, MutationType struct {
			Fields []struct{ Name string }
		}
	}
	mustUnmarshal(t, res.Data["__schema"], &sch)
	var names []string
	for _, root := range [][]struct{ Name string }{sch.QueryType.Fields, sch.MutationType.Fields} {
		for _, f := range root {
			names = append(names, f.Name)
		}
	}
	if !slices.Contains(names, "visibleFn") {
		t.Fatalf("visibleFn missing from root fields %v", names)
	}
	for _, n := range names {
		if n == "floatrange" || n == "floatmultirange" {
			t.Errorf("range constructor %q exposed as a root field", n)
		}
	}
}
