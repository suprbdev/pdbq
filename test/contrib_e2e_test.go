const (
	contribSchema    = "contrib_e2e"
	contribExtSchema = "contrib e2e ext"
)

// contribExtensions are the extensions the contrib suite installs (or
// reuses, when the database already has them elsewhere).
var contribExtensions = []string{"citext", "hstore", "ltree", "pg_trgm"}

// setupContrib creates the contrib_e2e schema with a table covering every
// contrib column type, installing the extensions into a schema that needs
// quoting and is not on the search_path, so every extension operator,
// function and type must reach Postgres schema-qualified. Everything it
// creates is dropped when the test ends.
func setupContrib(t *testing.T) {
	t.Helper()
	url := os.Getenv("PDBQ_TEST_DATABASE_URL")
	if url == "" {
		t.Skip("PDBQ_TEST_DATABASE_URL not set; run `make test-e2e`")
	}
	ctx := context.Background()
	conn, err := pgx.Connect(ctx, url)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = conn.Close(ctx) })
	exec := func(sql string) {
		t.Helper()
		if _, err := conn.Exec(ctx, sql); err != nil {
			t.Fatalf("%s: %v", sql, err)
		}
	}
	var installed []string
	for _, ext := range contribExtensions {
		var exists bool
		if err := conn.QueryRow(ctx, `SELECT EXISTS (SELECT 1 FROM pg_extension WHERE extname = $1)`, ext).Scan(&exists); err != nil {
			t.Fatal(err)
		}
		if !exists {
			installed = append(installed, ext)
		}
	}
	t.Cleanup(func() {
		_, _ = conn.Exec(ctx, `DROP SCHEMA IF EXISTS `+contribSchema+` CASCADE`)
		for _, ext := range installed {
			_, _ = conn.Exec(ctx, `DROP EXTENSION IF EXISTS `+ext+` CASCADE`)
		}
		_, _ = conn.Exec(ctx, `DROP SCHEMA IF EXISTS "`+contribExtSchema+`" CASCADE`)
	})
	exec(`CREATE SCHEMA IF NOT EXISTS "` + contribExtSchema + `"`)
	for _, ext := range installed {
		exec(`CREATE EXTENSION ` + ext + ` SCHEMA "` + contribExtSchema + `"`)
	}
	var trgmSchema string
	if err := conn.QueryRow(ctx, `SELECT n.nspname FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace WHERE e.extname = 'pg_trgm'`).Scan(&trgmSchema); err != nil {
		t.Fatal(err)
	}
	ops := `"` + strings.ReplaceAll(trgmSchema, `"`, `""`) + `".`
	var b strings.Builder
	b.WriteString(`SET search_path TO ` + contribSchema + `, "` + contribExtSchema + `", public;
CREATE SCHEMA ` + contribSchema + `;
CREATE TABLE ` + contribSchema + `.documents (
	id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	title text NOT NULL,
	slug citext UNIQUE,
	search tsvector,
	attrs hstore,
	path ltree,
	label varchar,
	paths ltree[],
	during tstzrange,
	span int4range,
	avail int4multirange,
	price numrange,
	ip inet,
	net cidr,
	notes text
);
CREATE TABLE ` + contribSchema + `.doc_notes (
	id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	document_id int NOT NULL REFERENCES ` + contribSchema + `.documents(id),
	meta hstore,
	period daterange
);
CREATE INDEX ON ` + contribSchema + `.documents USING gin (title ` + ops + `gin_trgm_ops);
CREATE INDEX ON ` + contribSchema + `.documents USING gist (label ` + ops + `gist_trgm_ops);
CREATE INDEX ON ` + contribSchema + `.documents USING gin (search);
CREATE INDEX ON ` + contribSchema + `.documents USING gin (attrs);
CREATE INDEX ON ` + contribSchema + `.documents USING gist (path);
CREATE INDEX ON ` + contribSchema + `.documents USING gist (paths);
CREATE INDEX ON ` + contribSchema + `.documents USING gist (during);
CREATE INDEX ON ` + contribSchema + `.documents USING gist (span);
CREATE INDEX ON ` + contribSchema + `.documents USING gist (avail);
CREATE INDEX ON ` + contribSchema + `.documents USING gist (ip inet_ops);
CREATE INDEX ON ` + contribSchema + `.documents (net);
CREATE INDEX ON ` + contribSchema + `.doc_notes (document_id);
CREATE INDEX ON ` + contribSchema + `.doc_notes USING gin (meta);
INSERT INTO ` + contribSchema + `.documents (id, title, slug, search, attrs, path, label, paths, during, span, avail, price, ip, net) VALUES
	(1, 'PostgreSQL full text search', 'Hello', to_tsvector('english', 'The quick brown fox jumps over the lazy dog'),
	 'color=>red, size=>L', 'top.science.astronomy', 'postgres', '{top.a,x.y}',
	 '[2024-01-01 00:00:00+00,2024-02-01 00:00:00+00)', '[1,5)', '{[1,3),[5,7)}', '[9.99,19.99]', '10.0.0.5', '10.0.0.0/8'),
	(2, 'MySQL tuning guide', 'World', to_tsvector('english', 'A fox and a dog and another dog, dogs everywhere'),
	 'color=>blue', 'top.science.physics', 'postgis', '{top.b}',
	 '[2024-03-01 00:00:00+00,)', '[10,20)', '{[10,12)}', '(,5)', '192.168.1.1', '192.168.0.0/16'),
	(3, 'Cooking at home', 'other', to_tsvector('english', 'cat videos'),
	 NULL, 'top.art', 'mongo', NULL,
	 NULL, 'empty', '{}', NULL, '2001:db8::1', '2001:db8::/32');
CREATE FUNCTION ` + contribSchema + `.widen(r int4range, by int) RETURNS int4range IMMUTABLE LANGUAGE sql
	AS $$ SELECT int4range(lower(r) - by, upper(r) + by) $$;
CREATE FUNCTION ` + contribSchema + `.with_flag(h hstore) RETURNS hstore IMMUTABLE LANGUAGE sql
	SET search_path = "` + contribExtSchema + `", public
	AS $$ SELECT h || hstore('flag', '1') $$;
SELECT setval(pg_get_serial_sequence('` + contribSchema + `.documents', 'id'), 100);
`)
	exec(b.String())
	exec(`RESET search_path`)
}

func contribServer(t *testing.T, mutate func(*config.Config)) string {
	t.Helper()
	setupContrib(t)
	hs := testServer(t, func(cfg *config.Config) {
		cfg.Schema.Schemas = []string{contribSchema}
		if mutate != nil {
			mutate(cfg)
		}
	})
	return hs.URL
}

// docIDs extracts the ids of an allDocuments connection's nodes.
func docIDs(t *testing.T, raw json.RawMessage) []int {
	t.Helper()
	var conn struct {
		Nodes []struct {
			ID int `json:"id"`
		} `json:"nodes"`
	}
	mustUnmarshal(t, raw, &conn)
	out := make([]int, len(conn.Nodes))
	for i, n := range conn.Nodes {
		out[i] = n.ID
	}
	return out
}

