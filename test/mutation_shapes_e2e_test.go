// TestMutationShapes runs every table mutation kind in PostGraphile v4's
// shape (one input argument, clientMutationId in it and echoed by the
// payload) against a table named by an uncountable noun, so the single-row
// and bulk mutations must not share a name. It covers the input passed
// whole as a variable, nested writes through the patch, and keyed updates
// and deletes that match no row.
func TestMutationShapes(t *testing.T) {
	conn := testConn(t)
	execAll(t, conn,
		`CREATE TABLE ms_news (id integer PRIMARY KEY, slug text NOT NULL UNIQUE, title text NOT NULL, hits integer NOT NULL DEFAULT 0)`,
		`CREATE TABLE ms_notes (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, news_id integer NOT NULL REFERENCES ms_news (id), body text NOT NULL)`,
		`CREATE INDEX ms_news_title_idx ON ms_news (title)`,
		`CREATE INDEX ms_notes_news_id_idx ON ms_notes (news_id)`,
	)
	t.Cleanup(func() {
		_, _ = conn.Exec(context.Background(), `DROP TABLE ms_notes; DROP TABLE ms_news`)
	})
	hs := testServer(t, nil)

	t.Run("create", func(t *testing.T) {
		res := post(t, hs.URL, `mutation {
			createMsNews(input: {clientMutationId: "c1", msNews: {id: 1, slug: "a", title: "A"}}) { clientMutationId msNews { id slug hits } }
		}`, nil)
		expectField(t, res, "createMsNews", `{"clientMutationId": "c1", "msNews": {"id": 1, "slug": "a", "hits": 0}}`)
	})
	t.Run("create with the input as a variable", func(t *testing.T) {
		res := post(t, hs.URL, `mutation ($in: CreateMsNewsInput!) { createMsNews(input: $in) { clientMutationId msNews { id } } }`,
			map[string]any{"in": map[string]any{"clientMutationId": "c2", "msNews": map[string]any{"id": 2, "slug": "b", "title": "B"}}})
		expectField(t, res, "createMsNews", `{"clientMutationId": "c2", "msNews": {"id": 2}}`)
	})
	t.Run("bulk create", func(t *testing.T) {
		res := post(t, hs.URL, `mutation {
			createManyMsNews(input: {clientMutationId: "m1", msNews: [{id: 3, slug: "c", title: "C"}, {id: 4, slug: "d", title: "D"}]}) {
				clientMutationId affectedCount msNews { id }
			}
		}`, nil)
		expectField(t, res, "createManyMsNews", `{"clientMutationId": "m1", "affectedCount": 2, "msNews": [{"id": 3}, {"id": 4}]}`)
	})
	t.Run("update by key and by unique key", func(t *testing.T) {
		res := post(t, hs.URL, `mutation {
			a: updateMsNewsById(input: {clientMutationId: "u1", id: 1, msNewsPatch: {title: "A2"}}) { clientMutationId msNews { title } }
			b: updateMsNewsBySlug(input: {slug: "b", msNewsPatch: {title: "B2"}}) { clientMutationId msNews { title } }
		}`, nil)
		expectField(t, res, "a", `{"clientMutationId": "u1", "msNews": {"title": "A2"}}`)
		expectField(t, res, "b", `{"clientMutationId": null, "msNews": {"title": "B2"}}`)
	})
	t.Run("upsert", func(t *testing.T) {
		res := post(t, hs.URL, `mutation {
			a: upsertMsNewsById(input: {clientMutationId: "s1", msNews: {id: 1, slug: "a", title: "A3"}}) { clientMutationId msNews { id title } }
			b: upsertMsNewsBySlug(input: {msNews: {id: 5, slug: "e", title: "E"}}) { msNews { id title } }
		}`, nil)
		expectField(t, res, "a", `{"clientMutationId": "s1", "msNews": {"id": 1, "title": "A3"}}`)
		expectField(t, res, "b", `{"msNews": {"id": 5, "title": "E"}}`)
	})
	t.Run("nested writes", func(t *testing.T) {
		res := post(t, hs.URL, `mutation {
			createMsNote(input: {msNote: {body: "n1", msNewsByNewsId: {connectBySlug: {slug: "a"}}}}) { msNote { body newsId } }
			updateMsNewsById(input: {id: 2, msNewsPatch: {msNotesByNewsId: {create: [{body: "n2"}]}}}) {
				msNews { msNotesByNewsId { nodes { body } } }
			}
		}`, nil)
		expectField(t, res, "createMsNote", `{"msNote": {"body": "n1", "newsId": 1}}`)
		expectField(t, res, "updateMsNewsById", `{"msNews": {"msNotesByNewsId": {"nodes": [{"body": "n2"}]}}}`)
	})
	t.Run("bulk update and delete", func(t *testing.T) {
		res := post(t, hs.URL, `mutation {
			updateManyMsNews(input: {clientMutationId: "m2", filter: {title: {in: ["C", "D"]}}, msNewsPatch: {hits: 7}}) { clientMutationId affectedCount }
			deleteManyMsNews(input: {clientMutationId: "m3", filter: {title: {equalTo: "E"}}}) { clientMutationId affectedCount msNews { id } }
		}`, nil)
		expectField(t, res, "updateManyMsNews", `{"clientMutationId": "m2", "affectedCount": 2}`)
		expectField(t, res, "deleteManyMsNews", `{"clientMutationId": "m3", "affectedCount": 1, "msNews": [{"id": 5}]}`)
	})
	t.Run("delete by key and by unique key", func(t *testing.T) {
		res := post(t, hs.URL, `mutation {
			a: deleteMsNewsById(input: {clientMutationId: "d1", id: 3}) { clientMutationId msNews { slug } deletedMsNewsNodeId }
			b: deleteMsNewsBySlug(input: {slug: "d"}) { msNews { id } }
		}`, nil)
		requireNoErrors(t, res)
		if got := normalize(t, res.Data["a"]); !strings.Contains(got, `"clientMutationId":"d1"`) || !strings.Contains(got, `"msNews":{"slug":"c"}`) || !strings.Contains(got, `"deletedMsNewsNodeId":"`) {
			t.Errorf("a = %s", got)
		}
		expectField(t, res, "b", `{"msNews": {"id": 4}}`)
	})
	t.Run("keyed update and delete matching no row", func(t *testing.T) {
		for _, q := range []string{
			`mutation { missing: updateMsNewsById(input: {id: 99, msNewsPatch: {title: "x"}}) { clientMutationId } }`,
			`mutation { missing: deleteMsNewsBySlug(input: {clientMutationId: "x", slug: "nope"}) { clientMutationId } }`,
		} {
			res := post(t, hs.URL, q, nil)
			if len(res.Errors) != 1 || res.Errors[0].Message != `no row matched "missing"` {
				t.Errorf("%s: errors = %+v", q, res.Errors)
			}
		}
	})
	t.Run("old shapes are rejected", func(t *testing.T) {
		for _, q := range []string{
			`mutation { updateMsNewsById(id: 1, patch: {title: "x"}) { clientMutationId } }`,
			`mutation { deleteMsNewsById(id: 1, clientMutationId: "x") { clientMutationId } }`,
			`mutation { createMsNews(input: {id: 9, slug: "z", title: "Z"}) { clientMutationId } }`,
		} {
			if res := post(t, hs.URL, q, nil); len(res.Errors) == 0 {
				t.Errorf("accepted %s", q)
			}
		}
	})
}

// TestMutationShapesSimpleNames checks the by-primary-key mutations
// simple_names shortens keep the single input argument, named after the
// short field.
func TestMutationShapesSimpleNames(t *testing.T) {
	hs := testServer(t, func(c *config.Config) {
		c.Plugins.Settings.SimpleNames.Enabled = true
	})
	res := post(t, hs.URL, `mutation ($in: UpdateUserInput!) { updateUser(input: $in) { clientMutationId user { id } } }`,
		map[string]any{"in": map[string]any{"clientMutationId": "sn", "id": 1, "userPatch": map[string]any{}}})
	if len(res.Errors) != 1 || !strings.Contains(res.Errors[0].Message, "userPatch must set at least one column") {
		t.Errorf("errors = %+v", res.Errors)
	}
	res = post(t, hs.URL, `mutation { deleteUser(input: {id: 999999}) { clientMutationId } }`, nil)
	if len(res.Errors) != 1 || !strings.Contains(res.Errors[0].Message, "no row matched") {
		t.Errorf("errors = %+v", res.Errors)
	}
}
