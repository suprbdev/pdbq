package config

import (
	"strings"

	"github.com/suprbdev/pdbcore/confx"
)

// ExampleYAML renders the fully-commented reference configuration from the
// Config struct tags and defaults, so the reference can never drift from the
// real config surface.
func ExampleYAML() string {
	var b strings.Builder
	b.WriteString("# pdbq reference configuration.\n")
	b.WriteString("# Generated by `pdbq config example` from the config structs — reference, not for direct use.\n")
	b.WriteString("# Every key is also settable via env (PDBQ_SECTION_KEY, double underscore for '_' in names)\n")
	b.WriteString("# or command-line flags; precedence is flags > env > file.\n\n")
	b.WriteString(confx.ExampleYAML(DefaultConfig()))
	return b.String()
}

// StarterYAML is the pdbq.yaml that `pdbq config init` writes: it runs
// with only database.url filled in, without credentials and as the
// connection role.
const StarterYAML = `# pdbq configuration. Run "pdbq config example" for the full annotated reference.
database:
  # Fill in real credentials, or delete the url and set PDBQ_DATABASE_URL.
  url: "postgres://USER:PASSWORD@HOST:5432/DB"
server:
  addr: ":8080"
schema:
  schemas: ["public"]
# Starter identity: no credentials, every request runs as the connection
# role. Configure auth (jwt or headers) and roles before production use;
# see "pdbq config example" and docs/rls.md.
auth:
  mode: none
roles:
  switch: false
`
